    /// 按码查文案（先查传输层，再查 SDK 层，最后查业务层）
    public static func message(for code: Int) -> String? {
        transportErrors[code] ?? sdkErrors[code] ?? businessErrors[code]
    }

    /// `04` 帧结果码的解释。
    ///
    /// **只对 `0x00` 有实测依据**；其余值不编造语义。
    /// 若该字节恰好等于某个 SDK/业务码，也只是「同数字」，不代表同一含义 ——
    /// 所以这里不做跨表映射。
    public static func describeResultByte(_ code: UInt8) -> String {
        if code == 0x00 { return "成功" }
        return String(format: "失败（0x%02X）· 该字节语义未在原 App 中找到解析代码", code)
    }
